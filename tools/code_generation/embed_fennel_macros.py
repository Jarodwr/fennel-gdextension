"""Generate src/generated/fennel_macros.gen.hpp from src/fennel-macros/*.fnl

Each .fnl file becomes one entry in FENNEL_MACROS[]. The entry holds the
filename (used for error messages) and the source text as a C string literal.
"""

import glob
import os
import sys


PROJECT_ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
MACROS_DIR = os.path.join(PROJECT_ROOT, "src", "fennel-macros")
OUTPUT = os.path.join(PROJECT_ROOT, "src", "generated", "fennel_macros.gen.hpp")


def c_string(s: str) -> str:
    """Escape a UTF-8 string as a C string literal (without surrounding quotes)."""
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    fnl_files = sorted(glob.glob(os.path.join(MACROS_DIR, "*.fnl")))
    if not fnl_files:
        print(f"WARNING: no .fnl files found in {MACROS_DIR}", file=sys.stderr)

    entries = []
    for path in fnl_files:
        name = os.path.basename(path)
        with open(path, encoding="utf-8") as f:
            source = f.read()
        entries.append((name, source))

    lines = [
        "// AUTO-GENERATED by tools/code_generation/embed_fennel_macros.py",
        "// Do not edit directly — edit .fnl files in src/fennel-macros/",
        "#pragma once",
        "",
        "struct EmbeddedFennelMacro {",
        "    const char* filename;",
        "    const char* source;",
        "};",
        "",
        "static const EmbeddedFennelMacro FENNEL_MACROS[] = {",
    ]
    for name, source in entries:
        lines.append(f'    {{"{name}", "{c_string(source)}"}},')
    lines.append("};")
    lines.append(f"static const int FENNEL_MACRO_COUNT = {len(entries)};")
    lines.append("")

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Generated {OUTPUT} ({len(entries)} macro(s))")


if __name__ == "__main__":
    main()
